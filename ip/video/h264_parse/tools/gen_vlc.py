#!/usr/bin/env python3
"""Writes ip/video/h264_parse/rtl/h264_vlc.v from the H.264 table
transcription in testdata/ip/h264_parse_vlc_tables.txt.

    python3 ip/video/h264_parse/tools/gen_vlc.py > ip/video/h264_parse/rtl/h264_vlc.v

The output is committed; tests/ip_h264_parse.rs drives every code of the
transcription through the generated module, so a stale or hand-edited
h264_vlc.v fails there.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TABLES = os.path.join(HERE, '..', '..', '..', '..', 'testdata', 'ip', 'h264_parse_vlc_tables.txt')

# The coeff_token columns the RTL decodes, by the class number `ct_cls`
# carries. nC == -2 is 4:2:2's chroma DC, which this parser does not take.
CT_CLASSES = [('0', 0), ('2', 1), ('4', 2), ('8', 3), ('-1', 4)]


def load():
    ct, tz, rb, cbp = {}, {}, {}, {'intra': {}, 'inter': {}}
    with open(TABLES) as f:
        for line in f:
            p = line.split()
            if not p or p[0].startswith('#'):
                continue
            if p[0] == 'coeff_token':
                ct.setdefault(p[1], []).append((p[4], int(p[2]), int(p[3])))
            elif p[0].startswith('total_zeros'):
                tz.setdefault((p[0][len('total_zeros'):], int(p[1])), []).append((p[3], int(p[2])))
            elif p[0] == 'run_before':
                rb.setdefault(int(p[1]), []).append((p[3], int(p[2])))
            elif p[0] in ('cbp_intra', 'cbp_inter'):
                cbp[p[0][4:]][int(p[1])] = int(p[2])
    return ct, tz, rb, cbp


def pattern(code, width):
    return "%d'b%s" % (width, code + '?' * (width - len(code)))


def main():
    ct, tz, rb, cbp = load()
    o = []
    w = o.append
    w('// h264_vlc -- the CAVLC variable-length codes of ITU-T H.264 and the')
    w('// coded_block_pattern mapping, as combinational decoders.')
    w('//')
    w('// GENERATED by ip/video/h264_parse/tools/gen_vlc.py from')
    w('// testdata/ip/h264_parse_vlc_tables.txt. Do not edit; regenerate.')
    w('//')
    w('// Each decoder looks at the next bits of the stream, most significant')
    w('// first, and says whether a code matches, how long it is and what it')
    w('// means. Bits past the end of the shortest match are ignored, so the')
    w('// caller passes the top of its bit window as it is.')
    w('//')
    w('//   coeff_token  (Table 9-5)  ct_cls: 0 for 0 <= nC < 2, 1 for 2 <= nC < 4,')
    w('//                             2 for 4 <= nC < 8, 3 for 8 <= nC, 4 for nC == -1')
    w('//   total_zeros  (Tables 9-7, 9-8, 9-9 (a))  tz_dc selects the chroma DC 2x2 VLCs;')
    w('//                             tz_tc is tzVlcIndex, the block\'s TotalCoeff')
    w('//   run_before   (Table 9-10) rb_zl is zerosLeft, 7 standing for every value > 6')
    w('//   coded_block_pattern (Table 9-4 (a)) for Intra_4x4/Intra_8x8 or Inter')
    w('module h264_vlc (')
    w('    input  wire [2:0]  ct_cls,')
    w('    input  wire [15:0] ct_bits,')
    w('    output reg         ct_valid,')
    w('    output reg  [4:0]  ct_len,')
    w('    // ct_len plus TrailingOnes: the code and the sign bits after it.')
    w('    output reg  [4:0]  ct_len1,')
    w('    output reg  [1:0]  ct_t1,')
    w('    output reg  [4:0]  ct_tc,')
    w('')
    w('    input  wire        tz_dc,')
    w('    input  wire [3:0]  tz_tc,')
    w('    input  wire [8:0]  tz_bits,')
    w('    output reg         tz_valid,')
    w('    output reg  [3:0]  tz_len,')
    w('    output reg  [3:0]  tz_val,')
    w('')
    w('    input  wire [2:0]  rb_zl,')
    w('    input  wire [10:0] rb_bits,')
    w('    output reg         rb_valid,')
    w('    output reg  [3:0]  rb_len,')
    w('    output reg  [3:0]  rb_val,')
    w('')
    w('    input  wire [5:0]  cbp_code,')
    w('    input  wire        cbp_inter,')
    w('    output reg         cbp_valid,')
    w('    output reg  [5:0]  cbp_val')
    w(');')
    w('')
    # coeff_token
    w('    always @* begin')
    w('        ct_valid = 1\'b0;')
    w('        ct_len   = 5\'d0;')
    w('        ct_len1  = 5\'d0;')
    w('        ct_t1    = 2\'d0;')
    w('        ct_tc    = 5\'d0;')
    w('        case (ct_cls)')
    for col, cls in CT_CLASSES:
        w('        3\'d%d: begin' % cls)
        w('            casez (ct_bits)')
        for code, t1, tc in sorted(ct[col], key=lambda e: (len(e[0]), e[0])):
            w('            %s: begin ct_valid = 1\'b1; ct_len = 5\'d%d; ct_len1 = 5\'d%d; ct_t1 = 2\'d%d; ct_tc = 5\'d%d; end'
              % (pattern(code, 16), len(code), len(code) + t1, t1, tc))
        w('            default: ;')
        w('            endcase')
        w('        end')
    w('        default: ;')
    w('        endcase')
    w('    end')
    w('')
    # total_zeros
    w('    always @* begin')
    w('        tz_valid = 1\'b0;')
    w('        tz_len   = 4\'d0;')
    w('        tz_val   = 4\'d0;')
    w('        case ({tz_dc, tz_tc})')
    for (cls, idx), rows in sorted(tz.items(), key=lambda e: (e[0][0], e[0][1])):
        if cls == '8':
            continue
        sel = (1 << 4 if cls == '4' else 0) | idx
        w('        5\'d%d: begin' % sel)
        w('            casez (tz_bits)')
        for code, val in sorted(rows, key=lambda e: (len(e[0]), e[0])):
            w('            %s: begin tz_valid = 1\'b1; tz_len = 4\'d%d; tz_val = 4\'d%d; end'
              % (pattern(code, 9), len(code), val))
        w('            default: ;')
        w('            endcase')
        w('        end')
    w('        default: ;')
    w('        endcase')
    w('    end')
    w('')
    # run_before
    w('    always @* begin')
    w('        rb_valid = 1\'b0;')
    w('        rb_len   = 4\'d0;')
    w('        rb_val   = 4\'d0;')
    w('        case (rb_zl)')
    for zl in sorted(rb):
        w('        3\'d%d: begin' % zl)
        w('            casez (rb_bits)')
        for code, val in sorted(rb[zl], key=lambda e: (len(e[0]), e[0])):
            w('            %s: begin rb_valid = 1\'b1; rb_len = 4\'d%d; rb_val = 4\'d%d; end'
              % (pattern(code, 11), len(code), val))
        w('            default: ;')
        w('            endcase')
        w('        end')
    w('        default: ;')
    w('        endcase')
    w('    end')
    w('')
    # cbp
    w('    always @* begin')
    w('        cbp_valid = 1\'b1;')
    w('        cbp_val   = 6\'d0;')
    w('        case ({cbp_inter, cbp_code})')
    for inter, name in ((0, 'intra'), (1, 'inter')):
        for code in sorted(cbp[name]):
            w('        7\'d%d: cbp_val = 6\'d%d;' % ((inter << 6) | code, cbp[name][code]))
    w('        default: cbp_valid = 1\'b0;')
    w('        endcase')
    w('    end')
    w('endmodule')
    sys.stdout.write('\n'.join(o) + '\n')


if __name__ == '__main__':
    main()
