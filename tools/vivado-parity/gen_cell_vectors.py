#!/usr/bin/env python3
"""Asks Vivado's simulator what each cell of src/fpga/devices/xc7_cells.v does.

For every module there, and for each variant of its parameters, this drives
the vendor's model with fixed pseudo-random inputs under `xsim` and writes
testdata/fpga/vivado/cells/<name>.v: a testbench holding the inputs and the
outputs that came back, which instantiates the cell by name and prints
`MISMATCH` if an output differs. Nothing of the vendor's model is written out,
only what it answered.

    tools/vivado-parity/gen_cell_vectors.py ~/Xilinx/2026.1/Vivado <workdir>
"""
import os, random, re, subprocess, sys
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LIB = os.path.join(ROOT, "src/fpga/devices/xc7_cells.v")
OUT = os.path.join(ROOT, "testdata/fpga/vivado/cells")
STEPS = 96
SETTLE = 200  # ns: the vendor's global reset lasts 100 ns.

# Modules whose inside is only other cells, or a pad: nothing to compare.
SKIP = {"BUFGP", "BUFGCE_1", "BUFGMUX_1"}
CLOCK_PORTS = {"C", "CLK", "WCLK", "G"}
ASYNC_PORTS = {"CLR", "PRE"}


def modules():
    text = open(LIB).read()
    for block in text.split("endmodule"):
        m = re.search(r"module\s+(\w+)\s*(#\((.*?)\)\s*)?\((.*?)\);", block, flags=re.S)
        if not m:
            continue
        params = []
        for p in re.finditer(r"parameter\s+\[(\d+):0\]\s+(\w+)", m.group(3) or ""):
            params.append((p.group(2), int(p.group(1)) + 1))
        ports = []
        direction, width = None, 1
        for part in re.split(r",", m.group(4)):
            d = re.match(r"\s*(input|output|inout)\s+(reg\s+)?(\[(\d+):0\]\s*)?(\w+)", part)
            if d:
                direction = d.group(1)
                width = int(d.group(4)) + 1 if d.group(4) else 1
                ports.append((direction, d.group(5), width))
            else:
                ports.append((direction, part.strip(), width))
        yield m.group(1), params, ports


def variants(params, rng):
    """The default, every INIT random, and each inversion on its own."""
    inits = [(n, w) for n, w in params if n.startswith("INIT")]
    inverted = [n for n, _ in params if n.startswith("IS_")]
    out = [("", {})]
    if inits:
        out.append(("_init", {n: f"{w}'h{rng.getrandbits(w):x}" for n, w in inits}))
    for name in inverted:
        out.append((f"_{name.lower()}", {name: "1'b1"}))
    # A simulation-only value: a `DNA_PORT`'s serial number, an `EFUSE_USR`'s bits.
    sims = [(n, w) for n, w in params if n.startswith("SIM_")]
    if sims:
        out.append(("_sim", {n: f"{w}'h{rng.getrandbits(w):x}" for n, w in sims}))
    return out


def write_tb(cell, tag, overrides, ports, first):
    inputs = [(n, w) for d, n, w in ports if d == "input"]
    outputs = [(n, w) for d, n, w in ports if d != "input"]
    iw = sum(w for _, w in inputs)
    ow = sum(w for _, w in outputs)
    lines = [f"// {cell}{(' ' + tag.strip('_')) if tag else ''}: inputs and Vivado's simulator's answers.",
             "// Generated by tools/vivado-parity/gen_cell_vectors.py.", "`timescale 1ns / 1ps", "module tb;"]
    lines.append(f"  reg [{iw - 1}:0] i = {iw}'h{first:x};")
    if ow:
        lines.append(f"  wire [{ow - 1}:0] o;")
    conns, at = [], 0
    for n, w in inputs:
        conns.append(f".{n}(i[{at + w - 1}:{at}])" if w > 1 else f".{n}(i[{at}])")
        at += w
    at = 0
    for n, w in outputs:
        conns.append(f".{n}(o[{at + w - 1}:{at}])" if w > 1 else f".{n}(o[{at}])")
        at += w
    params = ", ".join(f".{k}({v})" for k, v in overrides.items())
    lines.append(f"  {cell} {'#(' + params + ') ' if params else ''}dut ({', '.join(conns)});")
    return lines, iw, ow


def body(iw, ow, stim, answers=None):
    """A testbench's stimulus; with `answers`, checks them instead of printing."""
    if answers is None:
        out = ["  initial begin", f"    #{SETTLE};"]
        for n, s in enumerate(stim):
            out.append(f"    i = {iw}'h{s:x}; #10;")
            if ow:
                out.append(f'    $display("R {n} %h", o);')
        return out + ["    $finish;", "  end", "endmodule"]
    # `mask` clears what the vendor's model called unknown: not a question.
    out = ["  integer bad = 0;", "  integer n = 0;"]
    if ow:
        out += [f"  task t(input [{iw - 1}:0] v, input [{ow - 1}:0] want, input [{ow - 1}:0] mask);",
                "    begin",
                "      i = v; #10;",
                "      if ((o & mask) !== (want & mask)) begin",
                '        bad = bad + 1; $display("MISMATCH %0d %h", n, o);',
                "      end",
                "      n = n + 1;",
                "    end",
                "  endtask"]
    out += ["  initial begin", f"    #{SETTLE};"]
    full = (1 << ow) - 1 if ow else 0
    for n, s in enumerate(stim):
        if not ow:
            out.append(f"    i = {iw}'h{s:x}; #10;")
            continue
        a = answers[n]
        mask = int("".join("0" if c == "x" else "f" for c in a), 16) & full
        want = int(a.replace("x", "0"), 16)
        out.append(f"    t('h{s:x}, 'h{want:x}, 'h{mask:x});")
    out += ['    if (bad == 0) $display("PASS"); else $display("FAIL");', "    $finish;", "  end", "endmodule"]
    return out


def stimulus(ports, rng, falling):
    """Each step changes either the data inputs or the clocks, never both.

    A cell that acts on a falling edge starts with its clock high: a
    testbench's first value is an edge from unknown to some simulators and
    not to others, and it is not the cell that is being asked about then."""
    inputs = [(n, w) for d, n, w in ports if d == "input"]
    iw = sum(w for _, w in inputs)
    clock_bits = 0
    async_bits = 0
    at = 0
    for n, w in inputs:
        if n in CLOCK_PORTS:
            clock_bits |= ((1 << w) - 1) << at
        if n in ASYNC_PORTS:
            async_bits |= ((1 << w) - 1) << at
        at += w
    now = clock_bits if falling else 0
    out = []
    for step in range(STEPS):
        if step % 2 == 0:
            value = rng.getrandbits(iw) & ~clock_bits
            if rng.random() < 0.8:
                value &= ~async_bits
            now = (now & clock_bits) | value
        else:
            now ^= clock_bits
        out.append(now)
    return out, iw


def run(job):
    work, cell, tag, overrides, ports, seed = job
    rng = random.Random(seed)
    falling = cell.endswith("_1") or any(k in overrides for k in ("IS_C_INVERTED", "IS_CLK_INVERTED", "IS_WCLK_INVERTED"))
    stim, iw = stimulus(ports, rng, falling)
    ow = sum(w for d, _, w in ports if d != "input")
    name = f"{cell.lower()}{tag}"
    head, iw, ow = write_tb(cell, tag, overrides, ports, stim[0])
    d = os.path.join(work, name)
    os.makedirs(d, exist_ok=True)
    with open(f"{d}/tb.v", "w") as f:
        f.write("\n".join(head + body(iw, ow, stim)) + "\n")
    glbl = f"{sys.argv[1]}/data/verilog/src/glbl.v"
    script = (f". {sys.argv[1]}/settings64.sh >/dev/null 2>&1; cd {d}; "
              f"nice -n 19 ionice -c3 xvlog -sv tb.v {glbl} >x.log 2>&1 && "
              f"nice -n 19 ionice -c3 xelab -L unisims_ver -debug off tb glbl -s s >>x.log 2>&1 && "
              f"nice -n 19 ionice -c3 xsim s -R >out.log 2>&1")
    subprocess.run(["sh", "-c", script], check=False)
    try:
        lines = open(f"{d}/out.log").read().splitlines()
    except OSError:
        return name, None
    answers = {}
    for line in lines:
        m = re.match(r"R (\d+) (\S+)$", line)
        if m:
            answers[int(m.group(1))] = m.group(2).lower().replace("z", "x")
    if ow and len(answers) != STEPS:
        return name, None
    with open(f"{OUT}/{name}.v", "w") as f:
        f.write("\n".join(head + body(iw, ow, stim, answers)) + "\n")
    return name, True


def main():
    work = sys.argv[2]
    os.makedirs(OUT, exist_ok=True)
    jobs = []
    rng = random.Random(0x7c0)
    for cell, params, ports in modules():
        if cell in SKIP or any(d == "inout" for d, _, _ in ports):
            continue
        for tag, overrides in variants(params, rng):
            jobs.append((work, cell, tag, overrides, ports, rng.getrandbits(32)))
    with ThreadPoolExecutor(int(os.environ.get("JOBS", "24"))) as pool:
        results = list(pool.map(run, jobs))
    missing = [n for n, ok in results if not ok]
    print(len(results), "written;", len(missing), "the simulator would not run:", " ".join(missing))


main()
