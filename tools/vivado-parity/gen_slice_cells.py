#!/usr/bin/env python3
"""Writes the designs that ask Vivado what a latch and a shift register are in
a slice, into testdata/fpga/vivado/slice_cells/.

Each holds a few cells of one kind, written here, fed from a shift register of
flip-flops and read through a parity flip-flop, so that one design needs three
pins. `run_all.sh` runs them, `collect_slice_cells.py` keeps what the bitstream
decodes to, and `tests/fpga_xray_slice_cells.rs` holds Reticle to the answer.

    tools/vivado-parity/gen_slice_cells.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "testdata/fpga/vivado/slice_cells")

XDC = """create_clock -period 10 -name clk [get_ports clk]
set_property PACKAGE_PIN N11 [get_ports clk]
set_property PACKAGE_PIN L4 [get_ports si]
set_property PACKAGE_PIN L5 [get_ports so]
set_property IOSTANDARD LVCMOS33 [get_ports {clk si so}]
"""
RCF = """create_clock -name clk -period 10 clk
set_io -io_standard LVCMOS33 clk N11
set_io -io_standard LVCMOS33 si L4
set_io -io_standard LVCMOS33 so L5
"""


def probe(name, comment, body, inputs=16, outputs=1):
    """A design around `body`, which reads `sr` and drives `out`."""
    return name, (
        f"// {comment}\n// Generated by tools/vivado-parity/gen_slice_cells.py.\n"
        f"module {name} (\n    input  wire clk,\n    input  wire si,\n    output reg  so\n);\n"
        f"  reg [{inputs - 1}:0] sr;\n  wire [{outputs - 1}:0] out;\n"
        f"  always @(posedge clk) sr <= {{sr[{inputs - 2}:0], si}};\n"
        f"  reg q;\n  always @(posedge clk) q <= ^out;\n"
        f"  always @(posedge clk) so <= q ^ sr[0];\n"
        f"{body}"
        f"endmodule\n"
    )


def inst(cell, params, **pins):
    p = ", ".join(f".{k}({v})" for k, v in params.items())
    c = ", ".join(f".{k}({v})" for k, v in pins.items())
    return f"  {cell} {'#(' + p + ') ' if p else ''}dut ({c});\n"


DESIGNS = []


def add(name, comment, body, **kw):
    DESIGNS.append(probe(name, comment, body, **kw))


# Latches, by name: every form, and each parameter away from its default.
GATED = dict(Q="out[0]", D="sr[1]", G="sr[2]", GE="sr[3]")
add("ldce", "LDCE with its defaults.", inst("LDCE", {}, CLR="sr[0]", **GATED))
add("ldce_init1", "LDCE powering up holding one.", inst("LDCE", {"INIT": "1'b1"}, CLR="sr[0]", **GATED))
add("ldce_g_inv", "LDCE with an inverted gate.", inst("LDCE", {"IS_G_INVERTED": "1'b1"}, CLR="sr[0]", **GATED))
add("ldce_clr_inv", "LDCE with an inverted clear.", inst("LDCE", {"IS_CLR_INVERTED": "1'b1"}, CLR="sr[0]", **GATED))
add("ldce_1", "LDCE_1: open while the gate is low.", inst("LDCE_1", {}, CLR="sr[0]", **GATED))
add("ldpe", "LDPE with its defaults.", inst("LDPE", {}, PRE="sr[0]", **GATED))
add("ldpe_init0", "LDPE powering up holding zero.", inst("LDPE", {"INIT": "1'b0"}, PRE="sr[0]", **GATED))
add("ldpe_g_inv", "LDPE with an inverted gate.", inst("LDPE", {"IS_G_INVERTED": "1'b1"}, PRE="sr[0]", **GATED))
add("ldpe_1", "LDPE_1: open while the gate is low.", inst("LDPE_1", {}, PRE="sr[0]", **GATED))
PLAIN = dict(Q="out[0]", D="sr[1]", G="sr[2]")
add("ld", "LD: no enable, no clear.", inst("LD", {}, **PLAIN))
add("ld_init1", "LD powering up holding one.", inst("LD", {"INIT": "1'b1"}, **PLAIN))
add("ld_1", "LD_1.", inst("LD_1", {}, **PLAIN))
add("ldc", "LDC.", inst("LDC", {}, CLR="sr[0]", **PLAIN))
add("ldc_1", "LDC_1.", inst("LDC_1", {}, CLR="sr[0]", **PLAIN))
add("ldp", "LDP.", inst("LDP", {}, PRE="sr[0]", **PLAIN))
add("ldp_1", "LDP_1.", inst("LDP_1", {}, PRE="sr[0]", **PLAIN))
add("lde", "LDE.", inst("LDE", {}, GE="sr[3]", **PLAIN))
add("lde_1", "LDE_1.", inst("LDE_1", {}, GE="sr[3]", **PLAIN))
add("ldce_gclk", "LDCE gated by the global clock.",
    inst("LDCE", {}, Q="out[0]", D="sr[1]", G="clk", GE="sr[3]", CLR="sr[0]"))
add("ldce_two", "An LDCE and an LDPE with one control set.",
    "  LDCE a (.Q(out[0]), .D(sr[1]), .G(sr[2]), .GE(sr[3]), .CLR(sr[0]));\n"
    "  LDPE #(.INIT(1'b0)) b (.Q(out[1]), .D(sr[4]), .G(sr[2]), .GE(sr[3]), .PRE(sr[0]));\n", outputs=2)

# Latches, inferred: what `$dlatch` should become.
add("infer_latch", "An inferred latch.", "  reg l;\n  always @* if (sr[2]) l = sr[1];\n  assign out[0] = l;\n")
add("infer_latch_low", "An inferred latch, open while its gate is low.",
    "  reg l;\n  always @* if (!sr[2]) l = sr[1];\n  assign out[0] = l;\n")
add("infer_latch_clr", "An inferred latch with an asynchronous clear.",
    "  reg l;\n  always @* if (sr[0]) l = 1'b0; else if (sr[2]) l = sr[1];\n  assign out[0] = l;\n")
add("infer_latch_pre", "An inferred latch with an asynchronous preset.",
    "  reg l;\n  always @* if (sr[0]) l = 1'b1; else if (sr[2]) l = sr[1];\n  assign out[0] = l;\n")
add("infer_latch_en", "An inferred latch whose gate is an AND of two signals.",
    "  reg l;\n  always @* if (sr[2] && sr[3]) l = sr[1];\n  assign out[0] = l;\n")
add("infer_latch_init", "An inferred latch with an initial value.",
    "  reg l = 1'b1;\n  always @* if (sr[2]) l = sr[1];\n  assign out[0] = l;\n")
add("infer_latch_wide", "An inferred 10-bit latch, more than four slots of one slice.",
    "  reg [9:0] l;\n  always @* if (sr[2]) l = sr[13:4];\n  assign out = l;\n", outputs=10)

# Shift registers, by name.
INIT32 = "32'hF00FA5C3"
INIT16 = "16'hA5C3"
SR16 = dict(Q="out[0]", A0="sr[0]", A1="sr[1]", A2="sr[2]", A3="sr[3]", CE="sr[4]", CLK="clk", D="sr[5]")
SR16C = dict(SR16, Q15="out[1]")
SR32 = dict(Q="out[0]", A="sr[4:0]", CE="sr[5]", CLK="clk", D="sr[6]")
SR32C = dict(SR32, Q31="out[1]")
add("srl16e", "SRL16E with a variable address.", inst("SRL16E", {}, **SR16))
add("srl16e_init", "SRL16E with contents that say where each bit goes.", inst("SRL16E", {"INIT": INIT16}, **SR16))
add("srl16e_clk_inv", "SRL16E on the falling edge.", inst("SRL16E", {"IS_CLK_INVERTED": "1'b1"}, **SR16))
add("srl16e_1", "SRL16E_1.", inst("SRL16E_1", {}, **SR16))
add("srl16e_ce1", "SRL16E with its enable tied high.", inst("SRL16E", {}, **dict(SR16, CE="1'b1")))
add("srl16e_fixed15", "SRL16E at a fixed address: sixteen bits.",
    inst("SRL16E", {"INIT": INIT16}, **dict(SR16, A0="1'b1", A1="1'b1", A2="1'b1", A3="1'b1")))
add("srl16e_fixed0", "SRL16E at a fixed address: one bit.",
    inst("SRL16E", {"INIT": INIT16}, **dict(SR16, A0="1'b0", A1="1'b0", A2="1'b0", A3="1'b0")))
add("srl16", "SRL16.", inst("SRL16", {"INIT": INIT16}, **{k: v for k, v in SR16.items() if k != "CE"}))
add("srlc16", "SRLC16, its last bit read too.",
    inst("SRLC16", {"INIT": INIT16}, **{k: v for k, v in SR16C.items() if k != "CE"}), outputs=2)
add("srlc16e", "SRLC16E, its last bit read too.", inst("SRLC16E", {"INIT": INIT16}, **SR16C), outputs=2)
add("srlc16e_q15", "SRLC16E with only its last bit read.",
    inst("SRLC16E", {"INIT": INIT16}, **{k: v for k, v in dict(SR16, Q="", Q15="out[0]").items() if v}))
add("srlc32e", "SRLC32E with a variable address.", inst("SRLC32E", {"INIT": INIT32}, **SR32))
add("srlc32e_q31", "SRLC32E, its last bit read too.", inst("SRLC32E", {"INIT": INIT32}, **SR32C), outputs=2)
add("srlc32e_only_q31", "SRLC32E with only its last bit read.",
    inst("SRLC32E", {"INIT": INIT32}, **{k: v for k, v in dict(SR32, Q="", Q31="out[0]").items() if v}))
add("srlc32e_clk_inv", "SRLC32E on the falling edge.", inst("SRLC32E", {"IS_CLK_INVERTED": "1'b1"}, **SR32))
add("srlc32e_ce1", "SRLC32E with its enable tied high.", inst("SRLC32E", {}, **dict(SR32, CE="1'b1")))
add("srlc32e_fixed31", "SRLC32E at a fixed address: thirty-two bits.",
    inst("SRLC32E", {"INIT": INIT32}, **dict(SR32, A="5'd31")))
add("srlc32e_fixed5", "SRLC32E at a fixed address: six bits.",
    inst("SRLC32E", {"INIT": INIT32}, **dict(SR32, A="5'd5")))


def cascade(n):
    """`n` SRLC32Es, each's `Q31` the next's `D`; the last read at `sr[4:0]`."""
    text = f"  wire [{n}:0] link;\n  assign link[0] = sr[6];\n"
    for i in range(n):
        read = ".Q(out[0]), " if i == n - 1 else ""
        text += (f"  SRLC32E #(.INIT(32'h{0x80000001 + (i << 8):08X})) s{i} "
                 f"({read}.Q31(link[{i + 1}]), .A(sr[4:0]), .CE(sr[5]), .CLK(clk), .D(link[{i}]));\n")
    return text


add("srlc32e_cascade2", "Two SRLC32Es in a cascade.", cascade(2))
add("srlc32e_cascade4", "Four SRLC32Es in a cascade: a whole SLICEM.", cascade(4))
add("srlc32e_cascade5", "Five SRLC32Es in a cascade, which is more than one SLICEM.", cascade(5))
add("srl16e_two", "Two SRL16Es with one control set.",
    "  SRL16E #(.INIT(16'h1234)) a (.Q(out[0]), .A0(sr[0]), .A1(sr[1]), .A2(sr[2]), .A3(sr[3]), .CE(sr[4]), .CLK(clk), .D(sr[5]));\n"
    "  SRL16E #(.INIT(16'h5678)) b (.Q(out[1]), .A0(sr[0]), .A1(sr[1]), .A2(sr[2]), .A3(sr[3]), .CE(sr[4]), .CLK(clk), .D(sr[6]));\n",
    outputs=2)


# Shift registers, inferred: a chain of flip-flops, how long, and what stops it.
def chain(n, decl="", head="always @(posedge clk)", stmt=None, init="", tail=""):
    stmt = stmt or (f"c <= {{c[{n - 2}:0], sr[1]}};" if n > 1 else "c <= sr[1];")
    return (f"  {decl}reg [{n - 1}:0] c{init};\n  {head} {stmt}\n"
            f"  assign out[0] = c[{n - 1}];\n{tail}")


for n in (2, 3, 4, 5, 8, 16, 17, 18, 32, 33, 34, 35, 64, 66, 100):
    add(f"chain{n}", f"A chain of {n} flip-flops with no reset.", chain(n))
add("chain8_en", "A chain of eight with one enable.",
    chain(8, head="always @(posedge clk) if (sr[2])", stmt="c <= {c[6:0], sr[1]};"))
add("chain8_rst", "A chain of eight with a synchronous reset.",
    chain(8, stmt="if (sr[2]) c <= 8'd0; else c <= {c[6:0], sr[1]};"))
add("chain8_arst", "A chain of eight with an asynchronous reset.",
    chain(8, head="always @(posedge clk or posedge sr[2])", stmt="if (sr[2]) c <= 8'd0; else c <= {c[6:0], sr[1]};"))
add("chain8_set", "A chain of eight with a synchronous set.",
    chain(8, stmt="if (sr[2]) c <= 8'hff; else c <= {c[6:0], sr[1]};"))
add("chain8_init", "A chain of eight with initial values.", chain(8, init=" = 8'hA5"))
add("chain8_neg", "A chain of eight on the falling edge.", chain(8, head="always @(negedge clk)"))
add("chain8_tap", "A chain of eight read in the middle as well as at the end.",
    chain(8, tail="  assign out[1] = c[3];\n"), outputs=2)
add("chain8_tap_each", "A chain of eight with every stage read.",
    "  reg [7:0] c;\n  always @(posedge clk) c <= {c[6:0], sr[1]};\n  assign out = c;\n", outputs=8)
add("chain8_async_reg", "A chain of eight marked ASYNC_REG.", chain(8, decl='(* ASYNC_REG = "TRUE" *) '))
add("chain8_no_extract", "A chain of eight marked shreg_extract no.", chain(8, decl='(* shreg_extract = "no" *) '))
add("chain8_srl_reg", "A chain of eight marked srl_style register.", chain(8, decl='(* srl_style = "register" *) '))
add("chain8_keep", "A chain of eight marked keep.", chain(8, decl='(* keep = "true" *) '))
add("chain8_dont_touch", "A chain of eight marked dont_touch.", chain(8, decl='(* dont_touch = "true" *) '))
add("chain8_wide", "Eight stages of a four-bit word.",
    "  reg [3:0] w [0:7];\n  integer i;\n  always @(posedge clk) begin\n"
    "    w[0] <= sr[4:1];\n    for (i = 1; i < 8; i = i + 1) w[i] <= w[i - 1];\n  end\n  assign out = w[7];\n",
    outputs=4)
add("mem_shift", "A variable tap: a chain and an address that reads it.",
    "  reg [31:0] c;\n  always @(posedge clk) if (sr[5]) c <= {c[30:0], sr[6]};\n  assign out[0] = c[sr[4:0]];\n")
add("mem_shift16", "A variable tap into sixteen stages.",
    "  reg [15:0] c;\n  always @(posedge clk) if (sr[5]) c <= {c[14:0], sr[6]};\n  assign out[0] = c[sr[3:0]];\n")

# A chain between two pads with nothing beside it, to say how short one Vivado takes.
for n in (2, 3, 4):
    DESIGNS.append((f"pure{n}", (
        f"// {n} flip-flops between two pads, and nothing else.\n"
        f"// Generated by tools/vivado-parity/gen_slice_cells.py.\n"
        f"module pure{n} (input wire clk, input wire si, output wire so);\n"
        f"  reg [{n - 1}:0] c;\n  always @(posedge clk) c <= {{c[{n - 2}:0], si}};\n"
        f"  assign so = c[{n - 1}];\nendmodule\n")))

if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for name, text in DESIGNS:
        with open(os.path.join(OUT, name + ".v"), "w") as f:
            f.write(text)
        with open(os.path.join(OUT, name + ".xdc"), "w") as f:
            f.write(XDC)
        with open(os.path.join(OUT, name + ".rcf"), "w") as f:
            f.write(RCF)
    print(len(DESIGNS), "designs")
