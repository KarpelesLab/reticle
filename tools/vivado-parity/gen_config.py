PINS = {"clk": "N11", "si": "L4", "so": "L5"}

DESIGNS = {}
OPTS = {}


def named(params):
    return "#(" + ", ".join(f".{k}({v})" for k, v in params.items()) + ") " if params else ""


def add(name, comment, cell, conns, params=None, outputs=(), width=8, extra="", opts=None, loc=None, reads=()):
    """A design with one `cell` named `dut`. `conns` maps an input pin to what
    drives it, `sr[<n>]` or a constant; `outputs` maps an output pin to its
    width, and each reaches `so`."""
    lines = []
    wires = []
    for pin, w in outputs:
        wire = f"o_{pin.lower()}"
        lines.append(f"  wire [{w - 1}:0] {wire};" if w > 1 else f"  wire {wire};")
        wires.append(wire)
    pins = [f".{p}({v})" for p, v in conns.items()]
    pins += [f".{p}(o_{p.lower()})" for p, _ in outputs]
    body = "\n".join(lines) + ("\n" if lines else "")
    if cell:
        # A site asked for is an attribute both tools read, not a line of one
        # tool's constraints.
        at = f'(* LOC = "{loc}" *) ' if loc else ""
        body += f"  {at}{cell} {named(params)}dut ({', '.join(pins)});\n"
    body += extra
    reduce = " ^ ".join(f"(^{w})" for w in wires + list(reads)) or "1'b0"
    v = (
        f"// {comment} Generated by tools/vivado-parity/gen_config.py.\n"
        f"module {name} (\n"
        "    input  wire clk,\n"
        "    input  wire si,\n"
        "    output reg  so\n"
        ");\n"
        f"  reg [{width - 1}:0] sr;\n"
        f"  always @(posedge clk) sr <= {{sr[{width - 2}:0], si}};\n"
        + body
        + "  reg q;\n"
        f"  always @(posedge clk) q <= {reduce};\n"
        "  always @(posedge clk) so <= q ^ sr[0];\n"
        "endmodule\n"
    )
    DESIGNS[name] = v
    if opts:
        OPTS[name] = opts


