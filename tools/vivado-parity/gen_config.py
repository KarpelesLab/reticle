#!/usr/bin/env python3
"""Writes the designs of testdata/fpga/vivado/config/: `gen_config.py <dir>`.

Each asks Vivado one thing about a configuration primitive (`BSCANE2`,
`CAPTUREE2`, `DNA_PORT`, `EFUSE_USR`, `FRAME_ECCE2`, `ICAPE2`, `STARTUPE2`,
`USR_ACCESSE2`): one parameter away from a plain design, one wiring of its pins,
or one `write_bitstream` option beside it. `config.sh` runs them, and
`config_fixture.py` keeps what came back in `vivado.txt` there. Only answers are
committed, and these designs are written here.

Every design has the same three pins and a shift register `sr`, so that each
input is a real signal of the design's own and nothing is folded away, and each
output it reads reaches `so` through an exclusive-or and a flip-flop. A design
Vivado is expected to refuse is named `no_*`.

A design's bitstream options are in `<name>.opts`, one `NAME=VALUE` a line, which
is what `reticle fpga --bitstream-option` takes; its `.xdc` has the same as
`set_property`.
"""
